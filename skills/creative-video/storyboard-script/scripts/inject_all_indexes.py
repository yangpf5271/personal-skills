def inject_index(filepath, indices, index_header, tier):
    """读取文件，在头部插入索引，在每节前插入SECTION标记。"""
    with open(filepath, "r", encoding="utf-8") as f:
        original = f.read()

    # 检查是否已注入过
    if "══════ SECTION:" in original:
        print(f"  [SKIP] {os.path.basename(filepath)}: 已有索引，跳过")
        return

    # 插入SECTION标记
    modified = original
    for pattern, marker in indices:
        if pattern not in modified:
            print(f"  [WARN] 模式未找到: {pattern}")
            continue
        modified = modified.replace(
            pattern,
            f"══════════ {marker} ══════════\n{pattern}",
            1  # 只替换第一次出现
        )

    # 在文件最前面插入索引头
    modified = index_header + modified

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(modified)

    lines = modified.count("\n")
    size_kb = len(modified.encode("utf-8")) / 1024
    sections_found = sum(1 for _, m in indices if m in modified)
    print(f"  [{tier}] {os.path.basename(filepath)}: {sections_found}/{len(indices)} sections, {lines} lines, {size_kb:.1f} KB")


def main():
    for filename, indices, header, tier in TARGETS:
        filepath = os.path.join(BASE, filename)
        if not os.path.exists(filepath):
            print(f"  [SKIP] 文件不存在: {filename}")
            continue
        inject_index(filepath, indices, header, tier)

    print("\n[OK] 全部 7 个文件索引注入完成（中档3 + 重档4）")


if __name__ == "__main__":
    main()
